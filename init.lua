-- Finder that respects .gitignore
vim.api.nvim_create_user_command("Find", function(opts)
  local files = vim.fn.systemlist("fd --type f --hidden --exclude .git " .. opts.args)
  local file = files[1]
  if file and file ~= "" then
    vim.cmd("edit " .. file)
   else
    vim.cmd("edit " .. opts.args)
  end
end, {
  nargs = 1,
  complete = function(arg_lead)
    -- Run fd with the current typed partial (arg_lead)
    local result = vim.fn.systemlist("fd --type f --hidden --exclude .git " .. arg_lead)
    return result
  end,
})

-- Highlight yanked text
vim.api.nvim_create_autocmd("TextYankPost", {
  group = augroup,
  callback = function()
    vim.highlight.on_yank()
  end,
})

-- Return to last edit position when opening files
vim.api.nvim_create_autocmd("BufReadPost", {
  group = augroup,
  callback = function()
    local mark = vim.api.nvim_buf_get_mark(0, '"')
    local lcount = vim.api.nvim_buf_line_count(0)
    if mark[1] > 0 and mark[1] <= lcount then
      pcall(vim.api.nvim_win_set_cursor, 0, mark)
    end
  end,
})

-- Disable line numbers in terminal
vim.api.nvim_create_autocmd("TermOpen", {
  group = augroup,
  callback = function()
    vim.opt_local.number = false
    vim.opt_local.relativenumber = false
    vim.opt_local.signcolumn = "no"
  end,
})

-- Auto-resize splits when window is resized
vim.api.nvim_create_autocmd("VimResized", {
  group = augroup,
  callback = function()
    vim.cmd("tabdo wincmd =")
  end,
})

